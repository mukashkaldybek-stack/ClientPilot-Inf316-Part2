import client from 'prom-client';

// Create a dedicated Registry for ClientPilot metrics
export const register = new client.Registry();

// Enable default system metrics collection (CPU, Memory, Event Loop)
client.collectDefaultMetrics({
  register,
  prefix: 'clientpilot_',
});

// 1. Invoices Generated Counter
export const invoicesGeneratedCounter = new client.Counter({
  name: 'clientpilot_invoices_generated_total',
  help: 'Total count of invoices generated by ClientPilot',
  labelNames: ['status', 'currency'],
  registers: [register],
});

// 2. Total Time Tracked Hours Counter
export const timeTrackedHoursCounter = new client.Counter({
  name: 'clientpilot_time_tracked_hours_total',
  help: 'Total cumulative hours of billable work tracked across projects',
  labelNames: ['projectId', 'clientName'],
  registers: [register],
});

// 3. Active Running Timers Gauge
export const activeTimersGauge = new client.Gauge({
  name: 'clientpilot_active_timers',
  help: 'Current number of active running timers',
  registers: [register],
});

// 4. HTTP Request Duration Histogram
export const httpRequestDurationHistogram = new client.Histogram({
  name: 'clientpilot_http_request_duration_seconds',
  help: 'Duration of HTTP requests in seconds',
  labelNames: ['method', 'route', 'status'],
  buckets: [0.01, 0.05, 0.1, 0.25, 0.5, 1, 2.5, 5, 10],
  registers: [register],
});

// 5. PDF / Invoice Generation Duration Histogram
export const pdfGenerationDurationHistogram = new client.Histogram({
  name: 'clientpilot_pdf_generation_duration_seconds',
  help: 'Duration of PDF and invoice sheet generation in seconds',
  labelNames: ['status'],
  buckets: [0.05, 0.1, 0.25, 0.5, 1, 2, 5],
  registers: [register],
});

// 6. PDF Generation Errors Counter (for Alert Trigger #30)
export const pdfGenerationErrorsCounter = new client.Counter({
  name: 'clientpilot_pdf_generation_errors_total',
  help: 'Total number of invoice PDF generation failures or crashes',
  labelNames: ['reason'],
  registers: [register],
});

// Helper tracking methods
export function recordHttpRequestMetric(method: string, route: string, status: number, durationSeconds: number) {
  httpRequestDurationHistogram.observe({ method, route, status: String(status) }, durationSeconds);
}

export function recordInvoiceGenerated(currency: string = 'USD') {
  invoicesGeneratedCounter.inc({ status: 'success', currency });
}

export function recordTimeTracked(hours: number, projectId: string = 'default', clientName: string = 'Client') {
  timeTrackedHoursCounter.inc({ projectId, clientName }, hours);
}

export function updateActiveTimersCount(count: number) {
  activeTimersGauge.set(count);
}

export function recordPdfGenerationTime(durationSeconds: number, success: boolean = true, errorReason?: string) {
  if (success) {
    pdfGenerationDurationHistogram.observe({ status: 'success' }, durationSeconds);
  } else {
    pdfGenerationDurationHistogram.observe({ status: 'error' }, durationSeconds);
    pdfGenerationErrorsCounter.inc({ reason: errorReason || 'render_failure' });
  }
}

export async function getPrometheusMetrics(): Promise<string> {
  return await register.metrics();
}

export function getPrometheusContentType(): string {
  return register.contentType;
}
